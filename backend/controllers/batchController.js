// -----------------------------------------------
// MARK BATCH AS SOLD
// PUT /api/batch/retailer/:batchId/sold
// Only retailer can do this ✅
// -----------------------------------------------
export const markAsSold = asyncHandler(async (req, res) => {
  const { batchId } = req.params

  const batch = await Batch.findOne({ batchId })
  if (!batch) {
    throw new ApiError(404, "Batch not found")
  }

  // only retailer who added this batch can mark as sold
  if (batch.retailer.retailerId.toString() !== req.user._id.toString()) {
    throw new ApiError(403, "Only the retailer who received this batch can mark it as sold")
  }

  const blockchainHash = await recordOnBlockchain(
  batch.batchId,
  "retailer",
  req.user.name,
  "batch_sold"
)

  batch.retailer.isSold = true
  batch.currentStage = "completed"
  batch.latestBlockchainHash = blockchainHash

  batch.timeline.push({
  stage:            "retailer",
  message:          `Batch marked as sold by ${req.user.name}`,
  updatedBy:        req.user.name,
  blockchainHash:   blockchainHash,
  blockchainStatus: blockchainHash ? "confirmed" : "pending",
  timestamp:        new Date(),
})

  await batch.save()

  res.status(200).json(
    new ApiResponse(200, { batch }, "Batch marked as sold")
  )
})

