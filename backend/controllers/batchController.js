// -----------------------------------------------
// CREATE BATCH
// POST /api/batch/create
// Only farmer can do this ✅
// -----------------------------------------------
export const createBatch = asyncHandler(async (req, res) => {
  const {
    cropName,
    quantity,
    quantityUnit,
    location,
    harvestDate,
    pesticideUsed,
    village,
  } = req.body

  // Step 1 — validate required fields
  if (!cropName || !quantity || !location || !harvestDate) {
    throw new ApiError(400, "cropName, quantity, location, harvestDate are required")
  }

  // Step 2 — create batch in MongoDB
  // batchId is auto generated by pre("save") hook ✅
  const batch = await Batch.create({
    farmer: {
      farmerId: req.user._id,
      // req.user is set by protect middleware
      farmerName: req.user.name,
      village,
      cropName,
      quantity,
      quantityUnit: quantityUnit || "kg",
      location,
      harvestDate,
      pesticideUsed: pesticideUsed || "None",
      completedAt: new Date(),
    },
    currentStage: "farmer",
  })

  // Step 3 — generate QR code from batchId
  const qrCode = await generateQRCode(batch.batchId)

  // Step 4 — add timeline entry
  // blockchain hash is empty for now
  // we will add blockchain integration later

  // Step 4 — record on blockchain
const blockchainHash = await recordOnBlockchain(
  batch.batchId,
  "farmer",
  req.user.name,
  "batch_created"
)
// if blockchain fails → returns "" → app still works ✅

// Step 5 — add timeline entry with hash
  batch.qrCode = qrCode
  batch.latestBlockchainHash = blockchainHash


 batch.timeline.push({
  stage:           "farmer",
  message:         `Batch created by farmer ${req.user.name}`,
  updatedBy:       req.user.name,
  blockchainHash:  blockchainHash,
  blockchainStatus: blockchainHash ? "confirmed" : "pending",
  timestamp:       new Date(),
})

  // Step 5 — save updated batch
  await batch.save()

  res.status(201).json(
    new ApiResponse(
      201,
      { batch },
      "Batch created successfully"
    )
  )
})

// -----------------------------------------------
// UPDATE PROCESSOR STAGE
// PUT /api/batch/processor/:batchId
// Only processor can do this ✅
// -----------------------------------------------
export const updateProcessor = asyncHandler(async (req, res) => {
  const { batchId } = req.params
  const {
    facilityName,
    processingDate,
    packagingType,
    qualityGrade,
    additionalNotes,
  } = req.body

  // Step 1 — validate fields
  if (!facilityName || !processingDate || !packagingType || !qualityGrade) {
    throw new ApiError(400, "facilityName, processingDate, packagingType, qualityGrade are required")
  }

  // Step 2 — find batch
  const batch = await Batch.findOne({ batchId })
  if (!batch) {
    throw new ApiError(404, "Batch not found")
  }

  // Step 3 — check correct stage
  // processor can only update if batch is at farmer stage
  if (batch.currentStage !== "farmer") {
    throw new ApiError(
      400,
      `Batch is at ${batch.currentStage} stage. Processor can only update after farmer stage`
    )
  }

  // Step 4 — update processor stage
  batch.processor = {
    processorId: req.user._id,
    processorName: req.user.name,
    facilityName,
    processingDate,
    packagingType,
    qualityGrade,
    additionalNotes: additionalNotes || "",
    completedAt: new Date(),
  }

  // After updating batch.processor
// Add blockchain recording:
const blockchainHash = await recordOnBlockchain(
  batch.batchId,
  "processor",
  req.user.name,
  "batch_processed"
)

  // Step 5 — move to next stage
  batch.currentStage = "processor"
  batch.latestBlockchainHash = blockchainHash

  // Step 6 — add timeline entry
 batch.timeline.push({
  stage:            "processor",
  message:          `Batch processed by ${req.user.name} at ${facilityName}`,
  updatedBy:        req.user.name,
  blockchainHash:   blockchainHash,
  blockchainStatus: blockchainHash ? "confirmed" : "pending",
  timestamp:        new Date(),
})
  // Step 7 — save
  await batch.save()

  res.status(200).json(
    new ApiResponse(
      200,
      { batch },
      "Processor stage updated successfully"
    )
  )
})

